// TEST 4: Student Quiz Workflow
// ============================================
async function testStudentQuizWorkflow() {
  console.log('\n🧪 TEST 4: Student Quiz Workflow');
  console.log('=====================================');
  
  try {
    // 4.1 Student views available quizzes
    console.log('📋 4.1 Student viewing quizzes...');
    const listRes = await apiRequest('/api/quizzes/student', {
      headers: { 'Authorization': `Bearer ${TEST_CONFIG.studentToken}` }
    });
    
    if (listRes.success) {
      console.log('✅ Student view quizzes: SUCCESS');
      console.log(`   Found ${listRes.data?.length || 0} available quizzes`);
    } else {
      console.log('❌ Student view quizzes: FAILED');
      console.log('   Error:', listRes.message);
      return false;
    }
    
    // 4.2 Student attempts quiz (if quiz exists)
    if (TEST_CONFIG.testQuizId) {
      console.log('\n📋 4.2 Student attempting quiz...');
      const attemptRes = await apiRequest(`/api/quizzes/${TEST_CONFIG.testQuizId}/submit`, {
        method: 'POST',
        headers: { 'Authorization': `Bearer ${TEST_CONFIG.studentToken}` },
        body: JSON.stringify({
          answers: [
            { question_index: 0, selected_option: 2, time_spent_seconds: 10 },
            { question_index: 1, selected_option: 1, time_spent_seconds: 15 }
          ],
          started_at: new Date().toISOString()
        })
      });
      
      if (attemptRes.success) {
        console.log('✅ Quiz submission: SUCCESS');
        console.log('   Score:', attemptRes.data?.percentage || attemptRes.data?.score, '%');
        console.log('   Passed:', attemptRes.data?.passed ? 'YES' : 'NO');
      } else {
        console.log('❌ Quiz submission: FAILED');
        console.log('   Error:', attemptRes.message);
        // Don't fail the whole test if submission fails (might be out of attempts)
      }
    }
    
    return true;
  } catch (error) {
    console.log('❌ Student Quiz workflow test failed:', error);
    return false;
  }
}

