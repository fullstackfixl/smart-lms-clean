// TEST 2: AI Quiz Workflow
// ============================================
async function testAIQuizWorkflow() {
  console.log('\n🧪 TEST 2: AI Quiz Workflow');
  console.log('=====================================');
  
  try {
    // 2.1 Generate AI Quiz
    console.log('📋 2.1 Generating AI quiz...');
    const generateRes = await apiRequest('/api/quizzes/generate-ai', {
      method: 'POST',
      headers: { 'Authorization': `Bearer ${TEST_CONFIG.instructorToken}` },
      body: JSON.stringify({
        course_id: TEST_CONFIG.testCourseId,
        topic: 'Test Topic for AI Quiz',
        difficulty: 'medium',
        num_questions: 3
      })
    });
    
    if (generateRes.success) {
      console.log('✅ AI Quiz generation: SUCCESS');
      console.log('   Generated', generateRes.data?.questions?.length, 'questions');
    } else {
      console.log('❌ AI Quiz generation: FAILED');
      console.log('   Error:', generateRes.message);
      return false;
    }
    
    // 2.2 Create quiz from AI generated content
    console.log('\n📋 2.2 Creating quiz from AI content...');
    const createRes = await apiRequest(`/instructor/courses/${TEST_CONFIG.testCourseId}/quizzes`, {
      method: 'POST',
      headers: { 'Authorization': `Bearer ${TEST_CONFIG.instructorToken}` },
      body: JSON.stringify({
        title: 'AI Generated Test Quiz',
        description: 'Test quiz generated by AI',
        questions: generateRes.data?.questions || [],
        pass_percentage: 60,
        max_attempts: 3
      })
    });
    
    if (createRes.success) {
      TEST_CONFIG.testQuizId = createRes.data?._id || createRes.data?.quiz?._id;
      console.log('✅ Create quiz: SUCCESS');
      console.log('   Quiz ID:', TEST_CONFIG.testQuizId);
    } else {
      console.log('❌ Create quiz: FAILED');
      console.log('   Error:', createRes.message);
      return false;
    }
    
    // 2.3 List quizzes
    console.log('\n📋 2.3 Listing quizzes...');
    const listRes = await apiRequest(`/api/quizzes?course_id=${TEST_CONFIG.testCourseId}`, {
      headers: { 'Authorization': `Bearer ${TEST_CONFIG.instructorToken}` }
    });
    
    if (listRes.success) {
      const quizzes = listRes.data?.quizzes || listRes.data || [];
      console.log('✅ List quizzes: SUCCESS');
      console.log(`   Found ${quizzes.length} quizzes`);
      
      const found = quizzes.find((q: any) => q._id === TEST_CONFIG.testQuizId);
      if (found) {
        console.log('   ✅ Created quiz appears in list');
      }
    } else {
      console.log('❌ List quizzes: FAILED');
    }
    
    return true;
  } catch (error) {
    console.log('❌ AI Quiz workflow test failed:', error);
    return false;
  }
}

