// TEST 3: Manual Quiz Workflow
// ============================================
async function testManualQuizWorkflow() {
  console.log('\n🧪 TEST 3: Manual Quiz Workflow');
  console.log('=====================================');
  
  try {
    // 3.1 Create manual quiz
    console.log('📋 3.1 Creating manual quiz...');
    const createRes = await apiRequest(`/instructor/courses/${TEST_CONFIG.testCourseId}/quizzes`, {
      method: 'POST',
      headers: { 'Authorization': `Bearer ${TEST_CONFIG.instructorToken}` },
      body: JSON.stringify({
        title: 'Manual Test Quiz',
        description: 'Test quiz created manually',
        questions: [
          {
            question: 'What is 2+2?',
            options: ['1', '2', '4', '5'],
            correct_answer: 2
          },
          {
            question: 'What is the capital of France?',
            options: ['London', 'Berlin', 'Paris', 'Madrid'],
            correct_answer: 2
          }
        ],
        pass_percentage: 70,
        max_attempts: 2,
        status: 'draft'
      })
    });
    
    if (createRes.success) {
      const manualQuizId = createRes.data?._id || createRes.data?.quiz?._id;
      console.log('✅ Create manual quiz: SUCCESS');
      console.log('   Quiz ID:', manualQuizId);
      
      // 3.2 Edit the quiz
      console.log('\n📋 3.2 Editing quiz...');
      const editRes = await apiRequest(`/instructor/quizzes/${manualQuizId}`, {
        method: 'PUT',
        headers: { 'Authorization': `Bearer ${TEST_CONFIG.instructorToken}` },
        body: JSON.stringify({
          title: 'Manual Test Quiz (Edited)',
          description: 'Updated description',
          pass_percentage: 75
        })
      });
      
      if (editRes.success) {
        console.log('✅ Edit quiz: SUCCESS');
      } else {
        console.log('❌ Edit quiz: FAILED');
        console.log('   Error:', editRes.message);
      }
      
      // 3.3 Publish the quiz
      console.log('\n📋 3.3 Publishing quiz...');
      const publishRes = await apiRequest(`/api/quizzes/${manualQuizId}/publish`, {
        method: 'PATCH',
        headers: { 'Authorization': `Bearer ${TEST_CONFIG.instructorToken}` }
      });
      
      if (publishRes.success) {
        console.log('✅ Publish quiz: SUCCESS');
      } else {
        console.log('❌ Publish quiz: FAILED');
        console.log('   Error:', publishRes.message);
      }
    } else {
      console.log('❌ Create manual quiz: FAILED');
      console.log('   Error:', createRes.message);
      return false;
    }
    
    return true;
  } catch (error) {
    console.log('❌ Manual Quiz workflow test failed:', error);
    return false;
  }
}

