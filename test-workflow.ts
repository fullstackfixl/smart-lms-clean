const API_URL = process.env.NEXT_PUBLIC_API_URL || 'http://localhost:5000';

// Test Configuration
const TEST_CONFIG = {
  orgAdminToken: '',
  instructorToken: '',
  studentToken: '',
  organizationId: '',
  testBatchId: '',
  testCourseId: '',
  testQuizId: ''
};

// Helper: Make API requests
async function apiRequest(endpoint: string, options: any = {}) {
  const url = `${API_URL}${endpoint}`;
  const response = await fetch(url, {
    ...options,
    headers: {
      'Content-Type': 'application/json',
      ...options.headers
    }
  });
  return await response.json();
}

// ============================================
// TEST 1: Batches Workflow
// ============================================
async function testBatchesWorkflow() {
  console.log('\n🧪 TEST 1: Batches Workflow');
  console.log('=====================================');
  
  try {
    // 1.1 List batches (should not fail)
    console.log('📋 1.1 Listing batches...');
    const listRes = await apiRequest('/api/college/admin/batches', {
      headers: { 'Authorization': `Bearer ${TEST_CONFIG.orgAdminToken}` }
    });
    
    if (listRes.success) {
      console.log('✅ List batches: SUCCESS');
      console.log(`   Found ${listRes.data?.batches?.length || 0} batches`);
    } else {
      console.log('❌ List batches: FAILED');
      console.log('   Error:', listRes.message);
      return false;
    }
    
    // 1.2 Create batch
    console.log('\n📋 1.2 Creating test batch...');
    const createRes = await apiRequest('/api/college/admin/batches', {
      method: 'POST',
      headers: { 'Authorization': `Bearer ${TEST_CONFIG.orgAdminToken}` },
      body: JSON.stringify({
        name: 'Test Batch ' + Date.now(),
        code: 'TB' + Date.now().toString().slice(-4),
        programId: TEST_CONFIG.testCourseId,
        departmentId: '',
        year: 1,
        semester: 1,
        isActive: true
      })
    });
    
    if (createRes.success) {
      TEST_CONFIG.testBatchId = createRes.data?.batch?._id;
      console.log('✅ Create batch: SUCCESS');
      console.log('   Batch ID:', TEST_CONFIG.testBatchId);
    } else {
      console.log('❌ Create batch: FAILED');
      console.log('   Error:', createRes.message);
      return false;
    }
    
    // 1.3 Verify batch appears in list
    console.log('\n📋 1.3 Verifying batch appears in list...');
    const verifyRes = await apiRequest('/api/college/admin/batches', {
      headers: { 'Authorization': `Bearer ${TEST_CONFIG.orgAdminToken}` }
    });
    
    const found = verifyRes.data?.batches?.find((b: any) => b._id === TEST_CONFIG.testBatchId);
    if (found) {
      console.log('✅ Batch appears in list: VERIFIED');
    } else {
      console.log('⚠️  Batch not immediately visible (may need refresh)');
    }
    
    return true;
  } catch (error) {
    console.log('❌ Batches workflow test failed:', error);
    return false;
  }
}

