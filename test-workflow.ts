// MAIN TEST RUNNER
// ============================================
export async function runAllTests(config: typeof TEST_CONFIG) {
  console.log('\n' + '='.repeat(50));
  console.log('🚀 LMS WORKFLOW TEST SUITE');
  console.log('='.repeat(50));
  
  // Update config
  Object.assign(TEST_CONFIG, config);
  
  const results = {
    batches: await testBatchesWorkflow(),
    aiQuiz: await testAIQuizWorkflow(),
    manualQuiz: await testManualQuizWorkflow(),
    studentQuiz: await testStudentQuizWorkflow()
  };
  
  // Summary
  console.log('\n' + '='.repeat(50));
  console.log('📊 TEST SUMMARY');
  console.log('='.repeat(50));
  
  const allPassed = Object.values(results).every(r => r);
  
  Object.entries(results).forEach(([name, passed]) => {
    const icon = passed ? '✅' : '❌';
    console.log(`${icon} ${name}: ${passed ? 'PASSED' : 'FAILED'}`);
  });
  
  console.log('\n' + (allPassed ? '🎉 ALL TESTS PASSED!' : '⚠️ SOME TESTS FAILED'));
  console.log('='.repeat(50));
  
  return { allPassed, results };
}

